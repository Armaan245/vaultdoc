import { useState, useEffect } from 'react';
import { 
  GitPullRequest, 
  Send, 
  Check, 
  ExternalLink, 
  AlertCircle, 
  Settings, 
  Loader2
} from 'lucide-react';
import { 
  getStoredGitHubConfig, 
  createGitHubPullRequest, 
  fetchGitHubBranches,
  type GitHubConfig, 
  type PullRequestResponse 
} from '../services/github';

interface GitPRStudioProps {
  onOpenSettings: () => void;
}

export const GitPRStudio = ({ onOpenSettings }: GitPRStudioProps) => {
  const [config, setConfig] = useState<GitHubConfig>(getStoredGitHubConfig);
  const [branches, setBranches] = useState<string[]>([]);
  const [title, setTitle] = useState('feat(docs): update architecture specification & pre-pr shift-left tests');
  const [body, setBody] = useState(`## Summary of Changes
- Automated AST architecture specification generated by VaultDoc.
- Added shift-left security validation and edge-case unit test coverage.
- Zero cloud telemetry: verified 100% offline air-gapped processing.`);
  const [headBranch, setHeadBranch] = useState('feature/vaultdoc-specs');
  const [baseBranch, setBaseBranch] = useState('main');
  const [isDraft, setIsDraft] = useState(false);
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [createdPR, setCreatedPR] = useState<PullRequestResponse | null>(null);

  useEffect(() => {
    const handleConfigChange = () => {
      const updated = getStoredGitHubConfig();
      setConfig(updated);
      loadBranches(updated);
    };

    window.addEventListener('vaultdoc_github_config_change', handleConfigChange);
    loadBranches(config);

    return () => {
      window.removeEventListener('vaultdoc_github_config_change', handleConfigChange);
    };
  }, []);

  const loadBranches = async (cfg: GitHubConfig) => {
    if (cfg.pat && cfg.repoFullName && cfg.repoFullName.includes('/')) {
      const list = await fetchGitHubBranches(cfg);
      if (list.length > 0) {
        setBranches(list);
        if (list.includes(cfg.defaultBranch || 'main')) {
          setBaseBranch(cfg.defaultBranch || 'main');
        } else if (list[0]) {
          setBaseBranch(list[0]);
        }
      }
    }
  };

  const hasPat = Boolean(config.pat && config.pat.trim().length > 0);
  const hasRepo = Boolean(config.repoFullName && config.repoFullName.includes('/'));

  const handleCreatePR = async () => {
    setError(null);
    setCreatedPR(null);
    setIsSubmitting(true);
    try {
      const res = await createGitHubPullRequest({
        title,
        body,
        headBranch,
        baseBranch,
        isDraft
      });
      setCreatedPR(res);
    } catch (err: any) {
      setError(err.message || 'Failed to create Pull Request on GitHub');
    } finally {
      setIsSubmitting(false);
    }
  };

  return (
    <div className="flex-1 h-full bg-[#080d1a] flex flex-col overflow-hidden">
      {/* Top Header */}
      <div className="border-b border-vault-border bg-[#0b1224] px-6 py-3 flex items-center justify-between">
        <div className="flex items-center gap-2">
          <GitPullRequest className="w-5 h-5 text-cyan-400" />
          <div>
            <h2 className="text-xs font-bold text-white tracking-wide uppercase">
              Local-First GitHub Pull Request Client
            </h2>
            <p className="text-[10px] text-slate-400">
              Direct client-to-GitHub REST API dispatch with local-only PAT authentication
            </p>
          </div>
        </div>

        <div className="flex items-center gap-2">
          {(!hasPat || !hasRepo) && (
            <button
              onClick={onOpenSettings}
              className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-amber-500/15 border border-amber-500/30 text-amber-400 text-xs font-medium hover:bg-amber-500/25 transition-colors"
            >
              <Settings className="w-3.5 h-3.5" />
              <span>Configure GitHub PAT in Settings</span>
            </button>
          )}

          <button
            onClick={handleCreatePR}
            disabled={isSubmitting || !title.trim() || !hasPat || !hasRepo}
            className="flex items-center gap-1.5 px-4 py-1.5 rounded-lg text-xs font-bold bg-gradient-to-r from-cyan-500 to-blue-600 hover:from-cyan-400 hover:to-blue-500 text-black transition-all shadow-[0_0_12px_rgba(6,182,212,0.3)] active:scale-95 disabled:opacity-50"
          >
            {isSubmitting ? (
              <>
                <Loader2 className="w-3.5 h-3.5 animate-spin" />
                <span>Creating Pull Request...</span>
              </>
            ) : (
              <>
                <Send className="w-3.5 h-3.5" />
                <span>Create Local-First PR</span>
              </>
            )}
          </button>
        </div>
      </div>

      {/* Main Content Area */}
      <div className="flex-1 overflow-y-auto p-6 custom-scrollbar max-w-4xl mx-auto w-full space-y-5">
        
        {/* Token Alert Banner if not configured */}
        {(!hasPat || !hasRepo) && (
          <div className="p-4 bg-amber-950/40 border border-amber-500/40 rounded-xl flex items-start gap-3 text-xs text-amber-200">
            <AlertCircle className="w-5 h-5 text-amber-400 flex-shrink-0 mt-0.5" />
            <div className="flex-1">
              <h4 className="font-bold text-amber-300">GitHub Local Token Not Configured</h4>
              <p className="opacity-80 mt-0.5">
                To create pull requests directly from your machine without broad OAuth cloud risk, add your Fine-Grained Personal Access Token (PAT) and repository (e.g. <code>owner/repo</code>) in Settings [⚙️].
              </p>
              <button
                onClick={onOpenSettings}
                className="mt-2 px-3 py-1 bg-amber-500/20 hover:bg-amber-500/30 border border-amber-500/40 rounded text-amber-300 text-xs font-semibold"
              >
                Open Settings Modal
              </button>
            </div>
          </div>
        )}

        {/* Success Banner */}
        {createdPR && (
          <div className="p-4 bg-emerald-950/40 border border-emerald-500/40 rounded-xl flex items-start gap-3 text-xs text-emerald-200">
            <Check className="w-5 h-5 text-emerald-400 flex-shrink-0 mt-0.5" />
            <div className="flex-1">
              <h4 className="font-bold text-emerald-300">Pull Request Created Successfully! (#{createdPR.number})</h4>
              <p className="opacity-80 mt-0.5">{createdPR.title}</p>
              <a
                href={createdPR.html_url}
                target="_blank"
                rel="noreferrer"
                className="mt-2 inline-flex items-center gap-1.5 px-3 py-1 bg-emerald-500/20 hover:bg-emerald-500/30 border border-emerald-500/40 rounded text-emerald-300 text-xs font-semibold"
              >
                <span>View on GitHub</span>
                <ExternalLink className="w-3.5 h-3.5" />
              </a>
            </div>
          </div>
        )}

        {/* Error Banner */}
        {error && (
          <div className="p-4 bg-red-950/40 border border-red-500/40 rounded-xl flex items-start gap-3 text-xs text-red-200">
            <AlertCircle className="w-5 h-5 text-red-400 flex-shrink-0 mt-0.5" />
            <div className="flex-1">
              <h4 className="font-bold text-red-300">Pull Request Dispatch Failed</h4>
              <p className="opacity-80 mt-0.5 font-mono">{error}</p>
            </div>
          </div>
        )}

        {/* Repository & Branch Segment */}
        <div className="bg-[#0b1426] border border-vault-border rounded-xl p-4 grid grid-cols-3 gap-4 text-xs">
          <div>
            <label className="block text-slate-400 text-[11px] font-semibold uppercase mb-1">Target Repository</label>
            <input
              type="text"
              value={config.repoFullName || 'owner/repo (set in Settings)'}
              readOnly
              className="w-full bg-[#070b16] border border-vault-border rounded p-2 text-slate-300 font-mono text-xs cursor-default"
            />
          </div>

          <div>
            <div className="flex items-center justify-between mb-1">
              <label className="block text-slate-400 text-[11px] font-semibold uppercase">Base Branch</label>
              {branches.length > 0 && (
                <span className="text-[10px] text-cyan-400 font-mono">({branches.length} remote)</span>
              )}
            </div>
            <input
              type="text"
              list="branchList"
              value={baseBranch}
              onChange={(e) => setBaseBranch(e.target.value)}
              className="w-full bg-[#070b16] border border-vault-border rounded p-2 text-slate-200 font-mono text-xs focus:outline-none focus:border-cyan-400"
            />
          </div>

          <div>
            <label className="block text-slate-400 text-[11px] font-semibold uppercase mb-1">Head (Feature) Branch</label>
            <input
              type="text"
              list="branchList"
              value={headBranch}
              onChange={(e) => setHeadBranch(e.target.value)}
              className="w-full bg-[#070b16] border border-vault-border rounded p-2 text-slate-200 font-mono text-xs focus:outline-none focus:border-cyan-400"
            />
          </div>
          <datalist id="branchList">
            {branches.map(b => (
              <option key={b} value={b} />
            ))}
          </datalist>
        </div>

        {/* PR Title */}
        <div className="bg-[#0b1426] border border-vault-border rounded-xl p-4 text-xs space-y-3">
          <div>
            <label className="block text-slate-400 text-[11px] font-semibold uppercase mb-1">Pull Request Title</label>
            <input
              type="text"
              value={title}
              onChange={(e) => setTitle(e.target.value)}
              placeholder="e.g. feat(auth): add shift-left SQL injection and webhook checks"
              className="w-full bg-[#070b16] border border-vault-border rounded p-2.5 text-slate-200 text-xs focus:outline-none focus:border-cyan-400 font-medium"
            />
          </div>

          <div>
            <label className="block text-slate-400 text-[11px] font-semibold uppercase mb-1">PR Description (Markdown)</label>
            <textarea
              value={body}
              onChange={(e) => setBody(e.target.value)}
              rows={8}
              className="w-full bg-[#070b16] border border-vault-border rounded p-3 text-slate-200 font-mono text-xs focus:outline-none focus:border-cyan-400 resize-none leading-relaxed custom-scrollbar"
            />
          </div>

          <div className="flex items-center gap-2 pt-2">
            <input
              type="checkbox"
              id="draftCheck"
              checked={isDraft}
              onChange={(e) => setIsDraft(e.target.checked)}
              className="rounded bg-slate-800 border-vault-border text-cyan-400 focus:ring-0"
            />
            <label htmlFor="draftCheck" className="text-slate-300 text-xs cursor-pointer">
              Create as Draft Pull Request
            </label>
          </div>
        </div>
      </div>
    </div>
  );
};

export default GitPRStudio;
